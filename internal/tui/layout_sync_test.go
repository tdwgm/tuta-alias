package tui

import (
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// templateDir locates the Go template without going through $HOME.
//
// main_test.go points HOME at a temp directory so no test can touch the real
// config or cache. os.UserHomeDir() therefore returns that temp directory, and
// a template lookup built on it finds nothing and skips — which made the first
// version of this guard a silent no-op. runtime.Caller gives this file's own
// absolute path, compiled in, so the lookup works whatever HOME says:
//
//	<parent>/tuta-alias/internal/tui/layout_sync_test.go
//	<parent>/tui-cli-template/go/internal/tui/
func templateDir() string {
	if d := os.Getenv("GO_TUI_DIR"); d != "" {
		return filepath.Join(d, "go", "internal", "tui")
	}
	_, self, _, ok := runtime.Caller(0)
	if !ok {
		return ""
	}
	// internal/tui -> internal -> <project> -> <parent>
	parent := filepath.Dir(filepath.Dir(filepath.Dir(filepath.Dir(self))))
	for _, c := range []string{
		filepath.Join(parent, "go-tui", "go", "internal", "tui"),
		filepath.Join(parent, "tdwgm", "go-tui", "go", "internal", "tui"),
		filepath.Join(parent, "GO-TUI", "go", "internal", "tui"),
		filepath.Join(parent, "tui-cli-template", "go", "internal", "tui"),
	} {
		if fi, err := os.Stat(c); err == nil && fi.IsDir() {
			return c
		}
	}
	return ""
}

// updateSharedLayer renews testdata/shared_layer.sha256 from the files in this
// directory, once they match the template.
var updateSharedLayer = flag.Bool("update-shared-layer", false,
	"record new checksums for layout.go and font.go (needs the template checked out)")

// sharedLayerFiles are the files this project copies from the template, in the
// order the record lists them.
var sharedLayerFiles = []string{"layout.go", "font.go"}

// sharedLayerSums is the record of what those files held when they last
// matched the template. It is what keeps the guard working where the template
// is not checked out.
const sharedLayerSums = "testdata/shared_layer.sha256"

const sharedLayerHeader = `# SHA-256 of the files copied from the TUI Scaffold template (tdwgm/go-tui,
# go/internal/tui/), as TestSharedLayerMatchesTemplate computes them: layout.go
# whole, font.go with its comments and bannerFonts line removed (see
# normaliseShared). Do not edit by hand; the test says how to renew it.
`

// layout.go and font.go are NOT this project's files. They are the shared
// layer of the TUI Scaffold standard (tdwgm/go-tui, go/internal/tui/), and
// font.go is additionally generated by the skill's gen-banner-font.py.
//
// Without this test tuta-alias would be a silent copy: a fix made in the
// template would never arrive, and a local "quick change" here would never be
// noticed.
//
// The template is only checked out on a developer's machine, so comparing with
// it cannot be the guard: CI has no copy, and a test that skips there guards
// nothing where it matters. The guard is testdata/shared_layer.sha256, which
// records what each file held when it last matched the template. Every run
// compares our files with that record, so changing either one fails
// everywhere until the record is renewed, and the record is only renewed from
// files that match the template. When the template is checked out next to this
// project, or GO_TUI_DIR points at it, the files are also compared with it
// directly, which is what notices a change made in the template.
//
// When it fails: do NOT edit our copy to match by hand. Copy the template's
// file over ours, or, if the change belongs in the standard, change the
// template (or gen-banner-font.py) and copy from there. Then record the new
// checksums with
//
//	go test ./internal/tui -run TestSharedLayerMatchesTemplate -update-shared-layer
func TestSharedLayerMatchesTemplate(t *testing.T) {
	raw := map[string][]byte{}
	ours := map[string]string{}
	for _, name := range sharedLayerFiles {
		src, err := os.ReadFile(name)
		if err != nil {
			t.Fatalf("read %s: %v", name, err)
		}
		raw[name] = src
		ours[name] = normaliseShared(name, string(src))
	}
	tplDir := templateDir()

	if *updateSharedLayer {
		recordSharedLayer(t, tplDir, ours)
		return
	}

	recorded := readSharedLayerSums(t)
	for _, name := range sharedLayerFiles {
		if got := checksum(ours[name]); got != recorded[name] {
			t.Errorf("%s no longer matches the checksum recorded in %s.\n"+
				"  recorded: %q\n"+
				"  actual:   %q\n"+
				"It is the TUI Scaffold's file, not this project's. Copy the template's file over ours, "+
				"never patch ours by hand, then record the new checksum with\n"+
				"  go test ./internal/tui -run TestSharedLayerMatchesTemplate -update-shared-layer",
				name, sharedLayerSums, recorded[name], got)
		}
	}

	if tplDir == "" {
		t.Log("the template is not checked out here, so the files were compared with their recorded checksums only")
		return
	}
	for _, name := range sharedLayerFiles {
		want, err := os.ReadFile(filepath.Join(tplDir, name))
		if err != nil {
			t.Errorf("the template is expected at %s but has no readable %s: %v", tplDir, name, err)
			continue
		}
		if ours[name] != normaliseShared(name, string(want)) {
			t.Errorf("%s has drifted from the TUI Scaffold template.\n"+
				"  ours:     internal/tui/%s (%d bytes)\n"+
				"  template: %s (%d bytes)\n"+
				"Copy the template's file over ours; never patch ours by hand.",
				name, name, len(raw[name]), filepath.Join(tplDir, name), len(want))
		}
	}
}

// checksum is the SHA-256 of s as the record spells it.
func checksum(s string) string {
	sum := sha256.Sum256([]byte(s))
	return hex.EncodeToString(sum[:])
}

// readSharedLayerSums reads the record. One that is missing or unreadable
// fails the test: a guard with nothing to compare against must not pass.
func readSharedLayerSums(t *testing.T) map[string]string {
	t.Helper()
	raw, err := os.ReadFile(sharedLayerSums)
	if err != nil {
		t.Fatalf("read the recorded checksums: %v\n"+
			"record them with: go test ./internal/tui -run TestSharedLayerMatchesTemplate -update-shared-layer", err)
	}
	sums := map[string]string{}
	for line := range strings.SplitSeq(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 {
			t.Fatalf("%s: want \"<file> <sha256>\", got %q", sharedLayerSums, line)
		}
		sums[fields[0]] = fields[1]
	}
	return sums
}

// recordSharedLayer writes the record. It refuses unless the template is
// checked out and the copies match it, because a checksum taken from a file
// that does not match the template would turn the guard into a rubber stamp.
func recordSharedLayer(t *testing.T, tplDir string, ours map[string]string) {
	t.Helper()
	if tplDir == "" {
		t.Fatal("-update-shared-layer needs the template: set GO_TUI_DIR or clone tdwgm/go-tui next to this project")
	}
	var b strings.Builder
	b.WriteString(sharedLayerHeader)
	for _, name := range sharedLayerFiles {
		want, err := os.ReadFile(filepath.Join(tplDir, name))
		if err != nil {
			t.Fatalf("read the template's %s: %v", name, err)
		}
		if ours[name] != normaliseShared(name, string(want)) {
			t.Fatalf("%s does not match the template at %s: copy the template's file over ours first, "+
				"then record the checksums", name, tplDir)
		}
		fmt.Fprintf(&b, "%-10s %s\n", name, checksum(ours[name]))
	}
	if err := os.MkdirAll(filepath.Dir(sharedLayerSums), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(sharedLayerSums, []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("recorded %s", sharedLayerSums)
}

// normaliseShared decides what "identical" means per file.
//
// layout.go is compared byte for byte: it is the screen grammar and there is
// nothing legitimate to normalise away.
//
// font.go is compared as CODE ONLY (comments dropped), minus its bannerFonts
// declaration. Two differences there are deliberate and both are naming, not
// behaviour: the template's header line names a private path on the author's
// machine which this copy does not repeat, and the theme standard renamed the
// drawn logo from "default" to "logo" while the template has not caught up.
// bannerFonts is unused in this project — config.BannerFonts is the list the
// program actually reads — so the rename costs nothing here. The glyph table,
// fontBitmap and renderFont are still compared exactly, which is the part a
// template fix would land in.
func normaliseShared(name, src string) string {
	if name != "font.go" {
		return src
	}
	var out []string
	for _, line := range strings.Split(src, "\n") {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, "//") || strings.HasPrefix(t, "var bannerFonts") {
			continue
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}
